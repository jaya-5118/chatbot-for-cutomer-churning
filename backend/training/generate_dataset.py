def generate_dataset():
    """Generate the training dataset CSV file."""
    rows = []
    for intent, examples in INTENT_DATA.items():
        for text in examples:
            rows.append({"text": text, "intent": intent})

    # Shuffle with a reproducible seed
    random.seed(42)
    random.shuffle(rows)

    output_path = os.path.join(os.path.dirname(__file__), "dataset.csv")
    with open(output_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=["text", "intent"])
        writer.writeheader()
        writer.writerows(rows)

    # Print stats
    intent_counts = {}
    for row in rows:
        intent_counts[row["intent"]] = intent_counts.get(row["intent"], 0) + 1

    print(f"Dataset generated: {output_path}")
    print(f"Total examples: {len(rows)}")
    print(f"Number of intents: {len(intent_counts)}")
    print("\nExamples per intent:")
    for intent, count in sorted(intent_counts.items()):
        print(f"  {intent}: {count}")

    return rows


if __name__ == "__main__":
    generate_dataset()
